const read = (tree: Tree, path: string) => tree.read(path, 'utf-8') ?? '';

const listFiles = (tree: Tree, dir = ''): string[] =>
  tree.isFile(dir)
    ? [dir]
    : tree
        .children(dir)
        .filter((child) => dir !== '' || child !== 'node_modules')
        .flatMap((child) => listFiles(tree, dir ? `${dir}/${child}` : child));

const snapshotFiles = (tree: Tree) =>
  Object.fromEntries(listFiles(tree).map((path) => [path, read(tree, path)]));

/** A REST API project, as ts#smithy-api leaves it, with its CDK construct */
const addRestApi = async (tree: Tree) => {
  const declaration = declareDependencies()({
    ts: [...SHARED_CONSTRUCTS_DEPENDENCIES, ...API_CONSTRUCTS_DEPENDENCIES],
  });
  await sharedConstructsGenerator(tree, { iac: 'cdk' }, declaration);
  addProjectConfiguration(tree, '@proj/web-api', {
    root: 'packages/web-api/backend',
    metadata: { generator: 'ts#smithy-api', apiName: 'web-api', auth: 'iam' },
  } as Parameters<typeof addProjectConfiguration>[2]);
  await addApiGatewayInfra(
    tree,
    {
      iac: 'cdk',
      apiProjectName: '@proj/web-api',
      apiNameClassName: 'WebApi',
      apiNameKebabCase: 'web-api',
      constructType: 'rest',
      backend: {
        type: 'smithy',
        integrationPattern: 'isolated',
        bundleOutputDir: 'dist/packages/web-api/bundle',
      },
      auth: 'iam',
    },
    declaration,
  );
};

describe('ts#verified-access generator', () => {
  let tree: Tree;

  beforeEach(async () => {
    tree = createTreeUsingTsSolutionSetup();
    await addRestApi(tree);
  });

  it('should vend the door construct', async () => {
    await tsVerifiedAccessGenerator(tree, {
      apiProject: 'web-api',
      iac: 'cdk',
    });

    expect(read(tree, `${CONSTRUCTS_SRC}/core/index.ts`)).toContain(
      "export * from './verified-access.js';",
    );
    expect(tree.exists(`${CONSTRUCTS_SRC}/core/verified-access.ts`)).toBe(true);
  });

  it.each([
    [
      `${CONSTRUCTS_SRC}/core/user-identity.ts`,
      'LOCAL_CALLBACK_URLS.concat(findCloudFrontDomainNames(this))',
    ],
    [
      'packages/website/src/hooks/useSigV4.tsx',
      'awsClient.fetch(input, init);\nawsClient.sign(input, init);',
    ],
  ])(
    'should stop, and point at the migrations, when %s predates what it needs',
    async (path, old) => {
      addProjectConfiguration(tree, '@proj/website', {
        root: 'packages/website',
        sourceRoot: 'packages/website/src',
      });
      // Connected to the API
      tree.write('packages/website/src/hooks/useWebApi.tsx', '');
      tree.write(path, old);

      await expect(
        tsVerifiedAccessGenerator(tree, { apiProject: 'web-api', iac: 'cdk' }),
      ).rejects.toThrow(
        `${path} was generated by an older version of @aws/nx-plugin`,
      );
      expect(read(tree, path)).toBe(old);
      expect(tree.exists(`${CONSTRUCTS_SRC}/core/verified-access.ts`)).toBe(
        false,
      );
    },
  );

  it('should leave a website not connected to the API, whatever its hook', async () => {
    addProjectConfiguration(tree, '@proj/other', {
      root: 'packages/other',
      sourceRoot: 'packages/other/src',
    });
    tree.write('packages/other/src/hooks/useOtherApi.tsx', '');
    tree.write(
      'packages/other/src/hooks/useSigV4.tsx',
      'awsClient.fetch(input, init);\nawsClient.sign(input, init);',
    );

    await tsVerifiedAccessGenerator(tree, {
      apiProject: 'web-api',
      iac: 'cdk',
    });

    expect(tree.exists(`${CONSTRUCTS_SRC}/core/verified-access.ts`)).toBe(true);
  });

  it('should stop when the API construct grants as it used to', async () => {
    const path = `${CONSTRUCTS_SRC}/app/apis/web-api.ts`;
    tree.write(
      path,
      read(tree, path).replace(/Token\.compareStrings\([^)]*\)/, 'undefined'),
    );

    await expect(
      tsVerifiedAccessGenerator(tree, { apiProject: 'web-api', iac: 'cdk' }),
    ).rejects.toThrow(`${path} was generated by an older version`);
  });

  it('should change nothing when run again', async () => {
    await tsVerifiedAccessGenerator(tree, {
      apiProject: 'web-api',
      iac: 'cdk',
    });
    const before = snapshotFiles(tree);

    await tsVerifiedAccessGenerator(tree, {
      apiProject: 'web-api',
      iac: 'cdk',
    });

    expect(snapshotFiles(tree)).toEqual(before);
  });

  it('should refuse an HTTP API', async () => {
    addProjectConfiguration(tree, '@proj/http-api', {
      root: 'packages/http-api',
      metadata: { apiName: 'http-api', infra: 'http-lambda' },
    } as Parameters<typeof addProjectConfiguration>[2]);
    await expect(
      tsVerifiedAccessGenerator(tree, { apiProject: 'http-api', iac: 'cdk' }),
    ).rejects.toThrow('can only be served through a REST API');
  });

  it('should refuse terraform', async () => {
    await expect(
      tsVerifiedAccessGenerator(tree, {
        apiProject: 'web-api',
        iac: 'terraform' as 'cdk',
      }),
    ).rejects.toThrow('only supported with CDK');
  });

  it('should add generator metric to app.ts', async () => {
    await ensureAwsNxPluginConfig(tree);
    await updateAwsNxPluginConfig(tree, { metrics: true });
    await tsVerifiedAccessGenerator(tree, {
      apiProject: 'web-api',
      iac: 'cdk',
    });
    expectHasMetricTags(tree, TS_VERIFIED_ACCESS_GENERATOR_INFO.metric);
  });
});

interface ConstructsModule {
  readonly UserIdentity: new (
    scope: Construct,
    id: string,
  ) => {
    readonly identityPool: { readonly authenticatedRole: IGrantable };
    readonly userPool: unknown;
    readonly userPoolDomain: unknown;
    addCallbackUrl: (url: string) => void;
  };
  readonly WebApi: {
    new (
      scope: Construct,
      id: string,
      props: Record<string, unknown>,
    ): { readonly api: RestApi; grantInvokeAccess: (g: IGrantable) => void };
    defaultIntegrations: (scope: Construct) => { build: () => unknown };
  };
  readonly Website: new (
    scope: Construct,
    id: string,
    props: { api: { api: RestApi } },
  ) => { readonly url: string };
  readonly VerifiedAccess: new (
    scope: Construct,
    id: string,
    props: Record<string, unknown>,
  ) => { readonly url: string };
  readonly RuntimeConfig: {
    ensure: (scope: Construct) => { get: (ns: string) => Record<string, any> };
  };
}

const isolatedVpc = (scope: Construct) =>
  new Vpc(scope, 'Vpc', {
    maxAzs: 1,
    natGateways: 0,
    subnetConfiguration: [
      { name: 'Private', subnetType: SubnetType.PRIVATE_ISOLATED },
    ],
  });

describe('private API behind a Verified Access door', () => {
  const tmpDir = join(
    import.meta.dirname,
    `_tmp_verified-access-${process.pid}`,
  );
  let sources: string[];
  let template: Template;
  let stack: Stack;
  let module: ConstructsModule;
  let door: { readonly url: string };

  beforeAll(async () => {
    const tree = createTreeUsingTsSolutionSetup();
    await addRestApi(tree);
    await tsReactWebsiteGenerator(tree, {
      name: 'website',
      directory: 'packages',
      iac: 'cdk',
      ux: 'cloudscape',
      hosting: 'api-gateway',
      apiProject: 'web-api',
    });
    await addIdentityInfra(tree, {
      iac: 'cdk',
      cognitoDomain: 'test',
      allowSignup: true,
      localCallbackPorts: [4200],
    });
    await tsVerifiedAccessGenerator(tree, {
      apiProject: 'web-api',
      iac: 'cdk',
    });
    const metadata = `export const OPERATION_DETAILS = { echo: { path: '/echo', method: 'GET' } }`;
    sources = writeSharedConstructs(tree, tmpDir, {
      [`${CONSTRUCTS_SRC}/generated/web-api/metadata.gen.ts`]: `${metadata} as const;\nexport type Operations = keyof typeof OPERATION_DETAILS;\n`,
      [`${CONSTRUCTS_SRC}/generated/web-api/metadata.gen.js`]: `${metadata};\n`,
      'dist/packages/web-api/bundle/index.js': '',
      'dist/packages/website/bundle/index.html': '<html></html>',
      // Type checks the stack wiring the guide shows
      [`${CONSTRUCTS_SRC}/stack.ts`]: `import { Stack } from 'aws-cdk-lib';
import { Vpc } from 'aws-cdk-lib/aws-ec2';
import { HostedZone } from 'aws-cdk-lib/aws-route53';
import {
  UserIdentity,
  VerifiedAccess,
  type VerifiedAccessProps,
} from './core/index.js';
import { WebApi, Website } from './app/index.js';

export const wire = (stack: Stack) => {
  const identity = new UserIdentity(stack, 'Identity');
  const api = new WebApi(stack, 'WebApi', {
    integrations: WebApi.defaultIntegrations(stack).build(),
  });
  api.grantInvokeAccess(identity.identityPool.authenticatedRole);
  new Website(stack, 'Website', { api });
  return new VerifiedAccess(stack, 'Door', {
    api,
    identity,
    vpc: Vpc.fromLookup(stack, 'Vpc', { vpcId: 'vpc-0123456789abcdef0' }),
    hostedZone: HostedZone.fromHostedZoneAttributes(stack, 'Zone', {
      hostedZoneId: 'Z0000000000EXAMPLE',
      zoneName: 'example.com',
    }),
    recordName: 'app',
  });
};

// A door needs a VPC of yours
export const noVpc = (stack: Stack, props: Omit<VerifiedAccessProps, 'vpc'>) =>
  // @ts-expect-error vpc is required
  new VerifiedAccess(stack, 'NoVpc', props);
`,
    });
    module = await importSharedConstructs<ConstructsModule>(tmpDir);

    stack = new Stack(new App(), 'Test', {
      env: { account: '111111111111', region: 'ap-southeast-2' },
    });
    const identity = new module.UserIdentity(stack, 'Identity');
    const api = new module.WebApi(stack, 'WebApi', {
      integrations: module.WebApi.defaultIntegrations(stack).build(),
    });
    api.grantInvokeAccess(identity.identityPool.authenticatedRole);
    new module.Website(stack, 'Website', { api });
    door = new module.VerifiedAccess(stack, 'Door', {
      api,
      identity,
      vpc: isolatedVpc(stack),
      hostedZone: HostedZone.fromHostedZoneAttributes(stack, 'Zone', {
        hostedZoneId: 'Z0000000000EXAMPLE',
        zoneName: 'example.com',
      }),
      recordName: 'app',
    });
    template = Template.fromStack(stack);
  }, 120_000);

  afterAll(() => {
    rmSync(tmpDir, { recursive: true, force: true });
  });

  it('should compile', () => {
    expect(typeCheck(sources)).toEqual([]);
  }, 120_000);

  const endpointsOf = (t: Template) =>
    Object.keys(t.findResources('AWS::EC2::VPCEndpoint'));
  const privateTo = (t: Template) =>
    Object.values(t.findResources('AWS::ApiGateway::RestApi'))[0].Properties
      .EndpointConfiguration.VpcEndpointIds;

  it('should make the API private to the network endpoint', () => {
    const [restApi] = Object.values(
      template.findResources('AWS::ApiGateway::RestApi'),
    );
    expect(restApi.Properties.EndpointConfiguration).toEqual({
      Types: ['PRIVATE'],
      VpcEndpointIds: [
        { Ref: expect.stringMatching(/^DoorExecuteApiEndpoint/) },
      ],
    });
    const endpoint = {
      Ref: expect.stringMatching(/^DoorExecuteApiEndpoint/),
    };
    const statements = restApi.Properties.Policy.Statement as Record<
      string,
      unknown
    >[];
    expect(statements).toContainEqual(
      expect.objectContaining({
        Effect: 'Deny',
        Resource: 'execute-api:/*',
        Condition: { StringNotEquals: { 'aws:SourceVpce': endpoint } },
      }),
    );
    // The door allows nothing itself, so no principal of any account is
    // allowed the API's IAM operations by its policy: each caller needs its
    // own IAM policy, as grantInvokeAccess gives it
    for (const statement of statements.filter((st) => st.Effect === 'Allow')) {
      expect(statement.Resource).not.toEqual('execute-api:/*');
      if (statement.NotResource) {
        expect(statement.NotResource).toContain('execute-api:/*/GET/echo');
      } else {
        expect(statement.Resource).toEqual('execute-api:/*/OPTIONS/*');
      }
    }
    // Only the VPC the stack passes in, with the endpoint the door adds to it,
    // which admits the door alone, so nothing else in the VPC skips its sign-in
    template.resourceCountIs('AWS::EC2::VPC', 1);
    expect(endpointsOf(template)).toEqual([
      expect.stringMatching(/^DoorExecuteApiEndpoint/),
    ]);
    const endpointGroup = expect.stringMatching(
      /^DoorExecuteApiEndpointSecurityGroup/,
    );
    const ingress = [
      ...Object.entries(template.findResources('AWS::EC2::SecurityGroup'))
        .filter(([id]) => id.startsWith('DoorExecuteApiEndpointSecurityGroup'))
        .flatMap(([, sg]) => sg.Properties.SecurityGroupIngress ?? []),
      ...Object.values(template.findResources('AWS::EC2::SecurityGroupIngress'))
        .map((r) => r.Properties)
        .filter((r) =>
          JSON.stringify(r.GroupId).includes(
            'DoorExecuteApiEndpointSecurityGroup',
          ),
        ),
    ];
    expect(ingress).toEqual([
      expect.objectContaining({
        FromPort: 443,
        GroupId: { 'Fn::GetAtt': [endpointGroup, 'GroupId'] },
        SourceSecurityGroupId: {
          'Fn::GetAtt': [
            expect.stringMatching(/^DoorSecurityGroup/),
            'GroupId',
          ],
        },
      }),
    ]);
  });

  it('should redeploy the stage when the API is made private', () => {
    const plainStack = new Stack(new App(), 'Plain');
    new module.WebApi(plainStack, 'WebApi', {
      integrations: module.WebApi.defaultIntegrations(plainStack).build(),
    });
    const deploymentIds = (t: Template) =>
      Object.keys(t.findResources('AWS::ApiGateway::Deployment'));
    expect(deploymentIds(template)).not.toEqual(
      deploymentIds(Template.fromStack(plainStack)),
    );
  });

  const doorIn = (
    name: string,
    network: (scope: Stack) => Record<string, unknown>,
  ) => {
    const scope = new Stack(new App(), name);
    const identity = new module.UserIdentity(scope, 'Identity');
    const props = network(scope);
    const api = new module.WebApi(scope, 'WebApi', {
      integrations: module.WebApi.defaultIntegrations(scope).build(),
    });
    new module.VerifiedAccess(scope, 'Door', {
      api,
      identity,
      hostedZone: HostedZone.fromHostedZoneAttributes(scope, 'Zone', {
        hostedZoneId: 'Z0000000000EXAMPLE',
        zoneName: 'example.com',
      }),
      recordName: 'app',
      ...props,
    });
    return Template.fromStack(scope);
  };

  it('should use an execute-api endpoint given to it, and let the door reach it', () => {
    const t = doorIn('GivenEndpoint', (scope) => {
      const vpc = new Vpc(scope, 'Vpc', {
        maxAzs: 1,
        natGateways: 0,
        subnetConfiguration: [
          { name: 'Private', subnetType: SubnetType.PRIVATE_ISOLATED },
        ],
      });
      const endpoint = new InterfaceVpcEndpoint(scope, 'Shared', {
        vpc,
        service: InterfaceVpcEndpointAwsService.APIGATEWAY,
      });
      return { vpc, endpoint };
    });
    expect(endpointsOf(t)).toEqual([expect.stringMatching(/^Shared/)]);
    expect(privateTo(t)).toEqual([{ Ref: expect.stringMatching(/^Shared/) }]);
    expect(
      Object.values(t.findResources('AWS::EC2::SecurityGroupIngress')).map(
        (r) => r.Properties,
      ),
    ).toEqual([
      expect.objectContaining({
        FromPort: 443,
        GroupId: {
          'Fn::GetAtt': [
            expect.stringMatching(/^SharedSecurityGroup/),
            'GroupId',
          ],
        },
        SourceSecurityGroupId: {
          'Fn::GetAtt': [
            expect.stringMatching(/^DoorSecurityGroup/),
            'GroupId',
          ],
        },
      }),
    ]);
  });

  it('should refuse an API with a custom domain name', () => {
    const domainStack = new Stack(new App(), 'Domain');
    const identity = new module.UserIdentity(domainStack, 'Identity');
    const api = new module.WebApi(domainStack, 'WebApi', {
      integrations: module.WebApi.defaultIntegrations(domainStack).build(),
      domainName: {
        domainName: 'api.example.com',
        certificate: Certificate.fromCertificateArn(
          domainStack,
          'Cert',
          'arn:aws:acm:ap-southeast-2:111111111111:certificate/example',
        ),
      },
    });
    expect(
      () =>
        new module.VerifiedAccess(domainStack, 'Door', {
          api,
          identity,
          vpc: isolatedVpc(domainStack),
          hostedZone: HostedZone.fromHostedZoneAttributes(domainStack, 'Zone', {
            hostedZoneId: 'Z0000000000EXAMPLE',
            zoneName: 'example.com',
          }),
          recordName: 'app',
        }),
    ).toThrow(
      'A private API can be mapped only to a private custom domain name, and the door creates that domain itself',
    );

    // A public domain mapped after the door is found at synth
    const after = new Stack(new App(), 'DomainAfter');
    const afterApi = new module.WebApi(after, 'WebApi', {
      integrations: module.WebApi.defaultIntegrations(after).build(),
    });
    new module.VerifiedAccess(after, 'Door', {
      api: afterApi,
      identity: new module.UserIdentity(after, 'Identity'),
      vpc: isolatedVpc(after),
      hostedZone: HostedZone.fromHostedZoneAttributes(after, 'Zone', {
        hostedZoneId: 'Z0000000000EXAMPLE',
        zoneName: 'example.com',
      }),
      recordName: 'app',
    });
    afterApi.api.addDomainName('Domain', {
      domainName: 'api.example.com',
      certificate: Certificate.fromCertificateArn(
        after,
        'Cert',
        'arn:aws:acm:ap-southeast-2:111111111111:certificate/example',
      ),
    });
    expect(() => Template.fromStack(after)).toThrow(
      'A private API can be mapped only to a private custom domain name',
    );
  });

  it('should serve the API stage on the door domain', () => {
    template.hasResourceProperties('AWS::ApiGateway::DomainNameV2', {
      DomainName: 'app.example.com',
      EndpointConfiguration: { Types: ['PRIVATE'] },
    });
    template.hasResourceProperties('AWS::ApiGateway::BasePathMappingV2', {
      BasePath: 'prod',
    });
    template.resourceCountIs('AWS::ApiGateway::DomainNameAccessAssociation', 1);
    template.hasResourceProperties('AWS::EC2::VerifiedAccessEndpoint', {
      ApplicationDomain: 'app.example.com',
      EndpointDomainPrefix: 'app',
    });
    template.hasResourceProperties('AWS::Route53::RecordSet', {
      Name: 'app.example.com.',
      Type: 'CNAME',
    });
  });

  it('should point clients at the door, and let sign-in return there', () => {
    expect(door.url).toBe('https://app.example.com/prod/');
    expect(
      module.RuntimeConfig.ensure(stack).get('connection').apis.WebApi,
    ).toBe('https://app.example.com/prod/');
    const clients = Object.values(
      template.findResources('AWS::Cognito::UserPoolClient'),
    ).map((c) => c.Properties.CallbackURLs);
    expect(clients).toContainEqual(
      expect.arrayContaining(['https://app.example.com/prod/']),
    );
    expect(clients).toContainEqual([
      'https://app.example.com/oauth2/idpresponse',
    ]);
  });

  it('should open nothing to the internet', () => {
    const rules = Object.values(
      template.findResources('AWS::EC2::SecurityGroup'),
    ).flatMap((sg) => [
      ...(sg.Properties.SecurityGroupIngress ?? []),
      ...(sg.Properties.SecurityGroupEgress ?? []),
    ]);
    expect(rules.length).toBeGreaterThan(0);
    for (const rule of rules) {
      expect(rule.CidrIp).not.toBe('0.0.0.0/0');
      expect(rule.CidrIpv6).toBeUndefined();
    }
    template.resourceCountIs('AWS::EC2::InternetGateway', 0);
    template.resourceCountIs('AWS::EC2::NatGateway', 0);
  });

  it('should protect the door with a Web ACL and log it', () => {
    template.resourceCountIs('AWS::EC2::VerifiedAccessInstance', 1);
    expect(
      Object.values(
        template.findResources('AWS::WAFv2::LoggingConfiguration'),
      ).some((c) =>
        JSON.stringify(c.Properties.ResourceArn).includes('DoorWebAcl'),
      ),
    ).toBe(true);
    expect(
      Object.values(
        template.findResources('AWS::WAFv2::WebACLAssociation'),
      ).some((a) =>
        JSON.stringify(a.Properties.ResourceArn).includes(
          'verified-access-instance',
        ),
      ),
    ).toBe(true);
  });
});
