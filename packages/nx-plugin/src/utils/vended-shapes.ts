import type { Tree } from '@nx/devkit';
import { matchGritQL } from './ast.js';

export interface VendedShape {
  /** GritQL matching what the file has once migrated */
  readonly current: string;
  /** GritQL patterns the file as generated before matches, every one */
  readonly old: readonly string[];
}

/** UserIdentity's addCallbackUrl, and its scan for websites' signInCallbackUrls */
export const USER_IDENTITY_CALLBACK_URLS: VendedShape = {
  current:
    '`LOCAL_CALLBACK_URLS.concat($x)` where { $x <: contains `this.additionalCallbackUrls` }',
  old: [
    '`LOCAL_CALLBACK_URLS.concat($x)` where { $x <: contains `findCloudFrontDomainNames` }',
  ],
};

/** useSigV4 signing for API Gateway behind a custom domain */
export const SIGV4_CUSTOM_DOMAINS: VendedShape = {
  current: '`signingScope(input)`',
  old: ['`awsClient.fetch(input, init)`', '`awsClient.sign(input, init)`'],
};

/** RuntimeConfig's fetch under the app's base path */
export const RUNTIME_CONFIG_BASE_PATH: VendedShape = {
  current: '`import.meta.env.BASE_URL`',
  old: ["`fetch('/runtime-config.json')`"],
};

/** CognitoAuth's sign-in redirect under the app's base path */
export const COGNITO_AUTH_BASE_PATH: VendedShape = {
  // The deep-link callback, which only the migrated shape has, so a file patched by hand
  // for the base path alone is reported rather than taken as migrated
  current: '`onSigninCallback: $_`',
  old: ['`redirect_uri: window.location.origin`', '`auth.signinRedirect()`'],
};

/** The sign-out menu's redirects under the app's base path */
export const SIGN_OUT_BASE_PATH: VendedShape = {
  current: '`import.meta.env.BASE_URL`',
  old: ['`post_logout_redirect_uri: window.location.origin`'],
};

/**
 * Throws when the file at `path`, as an older version of the plugin generated
 * it, lacks what `generator` needs, as the plugin's migrations would add it.
 * The file is not changed. A missing file is left for its generator to add.
 */
export const assertVendedCurrent = async (
  tree: Tree,
  path: string,
  shape: VendedShape,
  needs: string,
  generator: string,
) => {
  if (!tree.exists(path) || (await matchGritQL(tree, path, shape.current))) {
    return;
  }
  throw new Error(
    `${path} was generated by an older version of @aws/nx-plugin and lacks ${needs}, which ${generator} needs. Run 'nx migrate @aws/nx-plugin' and apply the migrations, or make the change by hand, then run ${generator} again.`,
  );
};
